import os
import pandas as pd
from datetime import datetime, time
from backtest_engine import BacktestEngine

def main():
    top10 = [
        "RELIANCE", "HDFCBANK", "ICICIBANK", "INFY", "TCS",
        "ITC", "SBIN", "BHARTIARTL", "BAJFINANCE", "LT"
    ]
    data_dir = "data/nifty200"
    files = [os.path.join(data_dir, f"{s}_1m.csv") for s in top10 if os.path.exists(os.path.join(data_dir, f"{s}_1m.csv"))]
    
    target_date = "2026-04-17"
    print(f"🕒 Running Windowed Backtest for {target_date}...")
    
    engine = BacktestEngine(initial_capital=100000.0)
    engine.journal_file = "temp_journal.csv" # Temporary
    
    trades = engine.run_massive_backtest_v2(files, target_date=target_date)
    
    if not trades:
        print("No trades found for this day.")
        return

    # Define Windows
    windows = [
        ("09:15 - 09:45", time(9, 15), time(9, 45)),
        ("09:45 - 10:15", time(9, 45), time(10, 15)),
        ("10:15 - 10:45", time(10, 15), time(10, 45))
    ]
    
    for label, start, end in windows:
        filtered = []
        for t in trades:
            # entry time is in IST (converted by engine/adapter)
            # t['time'] is HH:MM string
            t_time = datetime.strptime(t['time'], "%H:%M").time()
            if start <= t_time < end:
                filtered.append(t)
        
        print(f"\n📊 WINDOW: {label}")
        if filtered:
            stats = engine.calculate_performance(filtered)
            print(f"   Trades: {stats['Total Trades']} | Wins: {stats['Wins']} | Losses: {stats['Losses']}")
            print(f"   Win Rate: {stats['Win Rate %']}% | PnL: {stats['Total Profit']} | RR: {stats['RR Ratio']}")
        else:
            print("   No trades in this window.")

    # Cleanup temp files
    if os.path.exists("temp_journal.csv"): os.remove("temp_journal.csv")
    # XLSX files are generated by engine.run_massive_backtest_v2 by default, 
    # we'll let them be for now as suppressing requires engine modification.

if __name__ == "__main__":
    main()
